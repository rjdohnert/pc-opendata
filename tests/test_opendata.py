class OpenDataTests(unittest.TestCase):
    source_layout = "modules"

    @classmethod
    def setUpClass(cls):
        compiler = os.environ.get("CC")
        command = ([compiler] if compiler and Path(compiler).is_file() else shlex.split(compiler)) if compiler else [
            shutil.which("clang") or shutil.which("cc") or ""
        ]
        if not command[0]:
            raise RuntimeError("A C11 compiler is required")
        cls.build = tempfile.TemporaryDirectory(prefix="opendata-build-")
        cls.addClassCleanup(cls.build.cleanup)
        cls.binary = Path(cls.build.name) / ("opendata.exe" if os.name == "nt" else "opendata")
        flags = [
            "-std=c11", "-Wall", "-Wextra", "-Wpedantic", "-Wconversion",
            "-Wshadow", "-Wstrict-prototypes", "-Werror", "-DOPENDATA_TESTING",
        ]
        if os.name != "nt":
            flags.append("-pthread")
        flags.extend(shlex.split(os.environ.get("OPENDATA_TEST_CFLAGS", "")))
        if cls.source_layout == "amalgamation":
            standalone = Path(cls.build.name) / "opendata.c"
            shutil.copyfile(ROOT / "src" / "opendata.c", standalone)
            sources = [standalone]
        else:
            names = (ROOT / "src" / "modules.txt").read_text(encoding="utf-8").splitlines()
            sources = [ROOT / "src" / name for name in names if name.strip()]
        result = subprocess.run(
            command + flags + [str(source) for source in sources] +
            (["-lws2_32", "-lsecur32", "-lcrypt32", "-lbcrypt"] if os.name == "nt" else ["-lcrypto", "-lm"]) +
            shlex.split(os.environ.get("OPENDATA_TEST_LDFLAGS", "")) + ["-o", str(cls.binary)],
            capture_output=True, text=True,
        )
        if result.returncode:
            raise RuntimeError(f"{cls.source_layout} build failed:\n{result.stdout}{result.stderr}")

    def test_amalgamation_matches_module_sources(self):
        source_dir = ROOT / "src"
        names = (source_dir / "modules.txt").read_text(encoding="utf-8").splitlines()
        self.assertEqual(len(names), len(set(names)), "Duplicate module in manifest")
        expected = "/* Generated by amalgamate.ps1. Edit the modules listed in src/modules.txt instead. */\n"
        for name in ["database_engine.h", *names]:
            content = (source_dir / name).read_text(encoding="utf-8")
            if name != "database_engine.h":
                include = '#include "database_engine.h"'
                self.assertTrue(content.startswith(include + "\n"))
                content = content[len(include):]
            expected += f'#line 1 "{name}"\n{content.rstrip(chr(10))}\n\n'
        self.assertEqual(
            (source_dir / "opendata.c").read_bytes(),
            expected.encode("utf-8"),
            "Run amalgamate.ps1 after changing module sources.",
        )

    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="opendata-test-")
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.database = self.root / "data.pcod"
        self.backups = self.root / "remote"
        self.backups.mkdir()

    def args(self, database=None, backup=None, interval=60):
        return [
            str(self.binary), "--database", str(database or self.database),
            "--backup-dir", str(backup or self.backups),
            "--backup-interval", str(interval),
        ]

    def run_sql(self, *statements, expected=0, env=None, database=None, extra=()):
        result = subprocess.run(
            self.args(database=database) + list(extra),
            input="\n".join((*statements, "EXIT", "")),
            text=True, encoding="utf-8", errors="replace", capture_output=True, timeout=20, env=env,
        )
        self.assertEqual(result.returncode, expected, result.stdout + result.stderr)
        return result

    def test_relational_join_and_durable_restart(self):
        self.run_sql(
            "CREATE TABLE parents (id NUMBER PRIMARY KEY, name VARCHAR2(40) NOT NULL);",
            "CREATE TABLE children (id NUMBER PRIMARY KEY, parent NUMBER REFERENCES parents(id));",
            "INSERT INTO parents VALUES (1, 'Smith, ''Bob''');",
            "INSERT INTO children VALUES (10, 1);",
            "COMMIT;",
        )
        result = self.run_sql(
            "SELECT parents.name, children.id FROM parents INNER JOIN children ON parents.id=children.parent;",
            "SELECT COUNT(*) FROM children WHERE parent=1;",
        )
        self.assertIn("PARENTS.NAME\tCHILDREN.ID\nSmith, 'Bob'\t10\n", result.stdout)
        self.assertIn("COUNT(*)\n1\n", result.stdout)

