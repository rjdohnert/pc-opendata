    def test_row_limit_and_snapshot_bounds(self):
        self.run_sql("CREATE TABLE t (n NUMBER);", "INSERT INTO t VALUES (1);", "COMMIT;")
        original = self.database.read_bytes()
        body = bytearray(original[:-4])
        # Skip the snapshot header and length-prefixed table name.
        offset = 28
        name_length = struct.unpack_from("<I", body, offset)[0]
        columns_offset = offset + 4 + name_length
        row_count_offset = columns_offset + 4
        # A NUMBER column with no reference and a one-byte value has a 9-byte row.
        extension_offset = body.index(b"USRCAT01")
        row_bytes = body[extension_offset - 9:extension_offset]
        body[extension_offset - 9:extension_offset] = row_bytes * 65536
        struct.pack_into("<I", body, row_count_offset, 65536)
        self.database.write_bytes(body + struct.pack("<I", zlib.crc32(body)))
        self.backups = self.root / "fixture-backups"
        self.backups.mkdir()
        result = self.run_sql(
            "INSERT INTO t VALUES (2);", "SELECT COUNT(*) FROM t;", expected=1
        )
        self.assertIn("row limit", result.stderr)
        self.assertIn("COUNT(*)\n65536\n", result.stdout)
        struct.pack_into("<I", body, row_count_offset, 65537)
        self.database.write_bytes(body + struct.pack("<I", zlib.crc32(body)))
        result = self.run_sql(expected=1)
        self.assertIn("corrupt", result.stderr)

