[CmdletBinding()]
param(
    [switch]$Check
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$sourceDirectory = Join-Path $PSScriptRoot 'src'
$manifest = Join-Path $sourceDirectory 'modules.txt'
$output = Join-Path $sourceDirectory 'opendata.c'
$encoding = New-Object System.Text.UTF8Encoding($false)
$moduleNames = @(Get-Content -LiteralPath $manifest | Where-Object { $_.Trim().Length -gt 0 })
if ($moduleNames.Count -eq 0) {
    throw 'The module manifest is empty.'
}
$seen = @{}
$files = @('database_engine.h')
foreach ($name in $moduleNames) {
    if ($name -notmatch '^[a-z][a-z0-9_]*\.c$' -or $name -eq 'opendata.c' -or $seen.ContainsKey($name)) {
        throw "Invalid or duplicate module in manifest: $name"
    }
    $seen[$name] = $true
    $files += $name
}

$text = New-Object System.Text.StringBuilder
[void]$text.Append("/* Generated by amalgamate.ps1. Edit the modules listed in src/modules.txt instead. */`n")
foreach ($name in $files) {
    $path = Join-Path $sourceDirectory $name
    $content = [System.IO.File]::ReadAllText($path, $encoding).Replace("`r`n", "`n").Replace("`r", "`n")
    if ($name -ne 'database_engine.h') {
        $include = '#include "database_engine.h"'
        if (-not $content.StartsWith($include + "`n")) {
            throw "$name must start with $include"
        }
        # Leave the include's newline in place so #line preserves module line numbers.
        $content = $content.Substring($include.Length)
    }
    [void]$text.Append("#line 1 `"$name`"`n")
    [void]$text.Append($content.TrimEnd([char[]]"`n"))
    [void]$text.Append("`n`n")
}

$expected = $encoding.GetBytes($text.ToString())
if ($Check) {
    if (-not [System.IO.File]::Exists($output)) {
        throw 'The amalgamation is missing. Run amalgamate.ps1.'
    }
    $actual = [System.IO.File]::ReadAllBytes($output)
    if ([Convert]::ToBase64String($actual) -cne [Convert]::ToBase64String($expected)) {
        throw 'The amalgamation is stale. Run amalgamate.ps1.'
    }
    Write-Host 'Amalgamation matches the module sources.'
    return
}

$temporary = "$output.$([Guid]::NewGuid().ToString('N')).tmp"
try {
    [System.IO.File]::WriteAllBytes($temporary, $expected)
    Move-Item -LiteralPath $temporary -Destination $output -Force
}
finally {
    if (Test-Path -LiteralPath $temporary) {
        Remove-Item -LiteralPath $temporary -Force
    }
}
Write-Host "Generated $output from $($moduleNames.Count) modules."
